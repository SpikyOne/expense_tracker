// Контракт репозитория категорий.
//
// Изолирует презентацию и будущее состояние (Riverpod) от деталей
// хранения: класс видит доменные модели и ничего не знает про SQLite.
// Сигнатуры сознательно повторяют CategoryDao - бизнес-правила (защита
// стандартных, перенос трат в "Без категории") остаются в DAO.

import 'package:expense_tracker/domain/models/models.dart';

/// Контракт доступа к категориям.
abstract class CategoryRepository {
  /// Все категории: стандартные по алфавиту ("Без категории" - последней
  /// среди стандартных), затем пользовательские по алфавиту.
  List<Category> getAll();

  /// Категория по id или null, если такой нет.
  Category? getById(int id);

  /// Вставляет пользовательскую категорию, возвращает её id.
  int insert(String name);

  /// Переименовывает пользовательскую категорию.
  void rename(int id, String name);

  /// Удаляет пользовательскую категорию; её траты переезжают в "Без категории".
  void delete(int id);
}
